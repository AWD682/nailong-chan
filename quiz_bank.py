# 兼容旧代码与测试：全部题目平铺。
FALLBACK_QUIZ_QUESTIONS: tuple[tuple[str, bool, str], ...] = tuple(
    question for questions in CATEGORY_QUIZ_QUESTIONS.values() for question in questions
)


def category_label(key: str) -> str | None:
    return QUIZ_CATEGORIES.get(key)


def questions_for_category(key: str) -> tuple[tuple[str, bool, str], ...]:
    return CATEGORY_QUIZ_QUESTIONS.get(key, FALLBACK_QUIZ_QUESTIONS)


def questions_for_categories(keys: tuple[str, ...] | list[str]) -> tuple[
        tuple[str, bool, str], ...]:
    """按选中的若干分类合并题库；分类非法时退回全库。"""
    valid = tuple(key for key in keys if key in CATEGORY_QUIZ_QUESTIONS)
    if not valid:
        return FALLBACK_QUIZ_QUESTIONS
    return tuple(question for key in valid
                 for question in CATEGORY_QUIZ_QUESTIONS[key])


def combined_category_label(keys: tuple[str, ...] | list[str]) -> str:
    """单分类显示分类名，多分类用顿号连接。"""
    labels = [QUIZ_CATEGORIES[key] for key in keys if key in QUIZ_CATEGORIES]
    return "、".join(labels) if labels else "混合"
